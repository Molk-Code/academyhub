// Writes firestore.<schoolId>.rules: firestore.rules with the deployment's
// school id swapped in (rules can't read env vars). Runs as the firestore
// predeploy step in firebase.<customer>.json, so every deploy uses the
// current rules. Molkom deploys firestore.rules itself.
//
//   node scripts/build-rules.mjs <schoolId>
import { readFileSync, writeFileSync } from 'fs'

const schoolId = process.argv[2]
if (!/^[a-z0-9-]{1,40}$/.test(schoolId ?? '')) {
  console.error('usage: node scripts/build-rules.mjs <schoolId>   (lowercase letters, digits, dashes)')
  process.exit(1)
}

const TEMPLATE_PATH = '/databases/$(database)/documents/schools/molkom)'
const src = readFileSync(new URL('../firestore.rules', import.meta.url), 'utf-8')
const count = src.split(TEMPLATE_PATH).length - 1
if (count !== 1) {
  console.error(`firestore.rules must reference the school exactly once (in schoolDoc()); found ${count}`)
  process.exit(1)
}
const out = src.replace(TEMPLATE_PATH, `/databases/$(database)/documents/schools/${schoolId})`)
const file = `firestore.${schoolId}.rules`
writeFileSync(new URL(`../${file}`, import.meta.url), `// GENERATED by scripts/build-rules.mjs from firestore.rules — do not edit\n${out}`)
console.log(`wrote ${file} (school ${schoolId})`)
